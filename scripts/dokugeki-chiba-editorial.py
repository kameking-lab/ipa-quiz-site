def common_explanations(q, spec=None):
    mode, data = spec or COMMON[q["year"], q["qNumber"]]
    correct = q["officialAnswerNumber"]-1
    if mode == "direct":
        assert len(data) == 5
        return list(data)
    labels = "アイウエオ"
    if mode == "tuple":
        expected = q["choices"][correct].split()
        assert len(expected) == len(data), q["id"]
        result = []
        for choice in q["choices"]:
            tokens = choice.split()
            assert len(tokens) == len(expected), q["id"]
            diffs = [i for i in range(len(tokens)) if tokens[i] != expected[i]]
            selected = diffs if diffs else range(len(tokens))
            result.append(" ".join(f"{labels[i]}は『{expected[i]}』。" + (f"『{tokens[i]}』ではない。" if i in diffs else "") + data[i] for i in selected))
        return result
    flags, basis = data
    assert len(flags) == len(basis)
    expected = [x == "T" for x in flags]
    result = []
    for choice in q["choices"]:
        if mode == "truth":
            actual = [x == "正" for x in choice.split()]
            assert len(actual) == len(expected), q["id"]
            diffs = [i for i in range(len(expected)) if actual[i] != expected[i]]
            parts = [f"{labels[i]}は{'正' if expected[i] else '誤'}。{basis[i]}" for i in (diffs if diffs else range(len(expected)))]
        else:
            selected = {labels.index(x) for x in re.findall(r"[アイウエ]", choice)}
            truth_set = {i for i,x in enumerate(expected) if x}
            assert len(truth_set) == 2
            diffs = sorted(selected ^ truth_set)
            parts = [f"{labels[i]}は{'正' if expected[i] else '誤'}。{basis[i]}" for i in (diffs if diffs else range(len(expected)))]
        result.append(" ".join(parts))
    # Author the factual pattern independently, then check against the official key.
    accepted = [i for i,c in enumerate(q["choices"]) if ([x == "正" for x in c.split()] == expected if mode == "truth" else {labels.index(x) for x in re.findall(r"[アイウエ]", c)} == {i for i,x in enumerate(expected) if x})]
    assert accepted == [correct], (q["id"], accepted, correct)
    return result


