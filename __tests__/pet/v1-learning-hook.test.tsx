import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { act, cleanup, renderHook } from "@testing-library/react";
import { usePetLearning } from "@/components/pet/usePetLearning";
import { preparePetOwner, persistBrowserPetAttempt } from "@/lib/pet/v1/runtime";
import type { Question } from "@/lib/questions/types";
import { LS_KEYS } from "@/lib/storage/keys";
import { browserPetSubmissions } from "@/lib/pet/v1/submission-order";
vi.mock("@/lib/pet/v1/runtime", () => ({ preparePetOwner: vi.fn(), persistBrowserPetAttempt: vi.fn() }));
const q = { id: "ap-q1", exam: "ap" } as Question;
let ownerScope = "guest";
beforeEach(() => {
  localStorage.clear(); vi.useFakeTimers(); ownerScope = "guest";
  vi.mocked(persistBrowserPetAttempt).mockReset();
  vi.mocked(preparePetOwner).mockReset();
  vi.mocked(preparePetOwner).mockImplementation(async current => ({ ownerScope, isCurrent: current, revalidate: async () => current() }));
});
afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks(); });
const settle = () => act(async () => { await vi.dynamicImportSettled(); });
it("defers persistence and preserves queued facts plus the combo session across focus/online refresh", async () => {
  const enqueue = vi.spyOn(browserPetSubmissions, "enqueue");
  const hook = renderHook(() => usePetLearning()); await settle();
  hook.result.current.answer(q, { kind: "multiple-choice", selected: ["ア"] });
  expect(persistBrowserPetAttempt).not.toHaveBeenCalled();
  act(() => { window.dispatchEvent(new Event("focus")); window.dispatchEvent(new Event("online")); }); await settle();
  await settle();
  hook.result.current.answer({ ...q, id: "ap-q2" }, { kind: "multiple-choice", selected: ["イ"] });
  await act(async () => { await vi.advanceTimersByTimeAsync(1000); }); await settle();
  await vi.waitFor(() => expect(enqueue).toHaveBeenCalledTimes(2));
  await Promise.all(enqueue.mock.results.map(result => result.value));
  const calls = vi.mocked(persistBrowserPetAttempt).mock.calls;
  expect(calls).toHaveLength(2);
  expect(calls[0][0].isCurrent()).toBe(true);
  expect(calls[0][1].sessionId).toBe(calls[1][1].sessionId);
  expect(calls[0][3].question.id).toBe("ap-q1"); expect(calls[1][3].question.id).toBe("ap-q2");
});
it("revokes pending facts when refresh discovers a different owner, without adopting them", async () => {
  const hook = renderHook(() => usePetLearning()); await settle();
  hook.result.current.answer(q, { kind: "multiple-choice", selected: ["ア"] });
  ownerScope = "user:other";
  act(() => window.dispatchEvent(new Event("focus"))); await settle();
  hook.result.current.answer({ ...q, id: "ap-q2" }, { kind: "multiple-choice", selected: ["ア"] });
  await act(async () => { await vi.advanceTimersByTimeAsync(1000); }); await settle();
  await vi.waitFor(() => expect(persistBrowserPetAttempt).toHaveBeenCalledTimes(2));
  const calls = vi.mocked(persistBrowserPetAttempt).mock.calls;
  expect(calls[0][0].ownerScope).toBe("guest"); expect(calls[0][0].isCurrent()).toBe(false);
  expect(calls[1][0].ownerScope).toBe("user:other"); expect(calls[1][0].isCurrent()).toBe(true);
});
it("copies the pre-answer snapshot using the existing SRS read", async () => {
  const hook = renderHook(() => usePetLearning()); await settle();
  const before = { id: q.id, ef: 2.5, reps: 1, intervalDays: 1, lastReviewedAt: 1700000000000, dueAt: 1700086400000 };
  localStorage.setItem(LS_KEYS.spacedRepetition, JSON.stringify({ cards: { [q.id]: before } }));
  const read = vi.spyOn(Storage.prototype, "getItem");
  hook.result.current.record(q, { kind: "multiple-choice", selected: ["ア"] }, true);
  expect(read.mock.calls.filter(([key]) => key === LS_KEYS.spacedRepetition)).toHaveLength(1);
  expect(persistBrowserPetAttempt).not.toHaveBeenCalled();
  await act(async () => { await vi.advanceTimersByTimeAsync(1000); }); await settle();
  expect(vi.mocked(persistBrowserPetAttempt).mock.calls[0][1].reviewBefore).toEqual({ lastReviewedAt: before.lastReviewedAt, dueAt: before.dueAt });
});
it("retains a current session through an unavailable refresh and later same-owner persistence", async () => {
  const enqueue = vi.spyOn(browserPetSubmissions, "enqueue");
  const hook = renderHook(() => usePetLearning()); await settle();
  hook.result.current.answer(q, { kind: "multiple-choice", selected: ["ア"] });
  vi.mocked(preparePetOwner).mockRejectedValueOnce(new Error("503"));
  act(() => window.dispatchEvent(new Event("focus"))); await settle();
  hook.result.current.answer({ ...q, id: "ap-q2" }, { kind: "multiple-choice", selected: ["イ"] });
  await act(async () => { await vi.advanceTimersByTimeAsync(1000); }); await settle();
  await Promise.all(enqueue.mock.results.map(result => result.value));
  const calls = vi.mocked(persistBrowserPetAttempt).mock.calls;
  expect(calls).toHaveLength(2);
  expect(calls[0][0].isCurrent()).toBe(true); expect(calls[1][0].isCurrent()).toBe(true);
  expect(calls[0][1].sessionId).toBe(calls[1][1].sessionId);
  expect(await calls[1][0].revalidate()).toBe(true);
});
