function publishedYearRange(exam: ExamCode): string {

    const years = getQuestionsByExamStrict(exam).map((q) => q.year);

    if (years.length === 0)

        return "掲載済み";

    const first = Math.min(...years);

    const last = Math.max(...years);

    return first === last ? `${first}年度` : `${first}〜${last}年度`;

}

export function examMetaDescription(exam: ExamCode, questionCount: number, mode?: "year" | "topic"): string {
    if (!mode && isIpaTop(exam)) return ipaTopDescription(exam, examFullName(exam), getQuestionsByExamStrict(exam));
    const name = EXAM_FULL_NAMES[exam];
    const questions = getQuestionsByExamStrict(exam);
    const yearCount = groupByYearSeason(questions).length;
    const categoryCount = groupByCategory(questions).length;
    const countFmt = questionCount.toLocaleString("ja-JP");
    // 一部収録の資格は「全○期分」と読める汎用文言を使わない。
    if (exam === "kokka-ippan-dai" || exam === "kokka-sogo-in" || exam === "toukei1" || exam === "literas" || exam === "cfp" || exam === "boueki-c" || exam === "service2" || exam === "apef3" || exam === "ishi" || exam === "chosashi" || exam === "shika-ishi" || exam === "sharoushi" || exam === "rinsho-kensagishi" || exam === "shinryo-hoshasengishi" || exam === "gijutsushi1-kensetsu")
        return EXAM_META_DESC_DIVERSE[exam](countFmt, yearCount, categoryCount);
    if (mode === "year") {

        return `${name}の年度別過去問${countFmt}問・${yearCount}期分・${categoryCount}分野を収録。実施回を選んで、問題・出典・学習用解説を確認できます。`;

    }
    if (mode === "topic") {

        return `${name}の分野別過去問${countFmt}問・${categoryCount}分野・${yearCount}期分を収録。分野を選んで、問題・出典・学習用解説を確認できます。`;

    }
    return EXAM_META_DESC_DIVERSE[exam](countFmt, yearCount, categoryCount);
}

