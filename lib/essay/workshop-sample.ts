function changeParagraph(section: readonly EssayParagraph[], index: number, original: string, replacement: string, heading?: string) {
  if (!section[index]?.text.includes(original)) throw new Error("Sample paragraph no longer contains the source text");
  return section.map((paragraph, i) => i === index
    ? { heading: heading ?? paragraph.heading, text: paragraph.text.replace(original, replacement) }
    : paragraph);
}

function manuscript(
  title: string,
  paragraphs: Record<SectionKey, readonly EssayParagraph[]>,
  reuse: EssayDraft["reuse"] = [],
  sectionTitles = titles,
): EssayDraft {
  const section = (key: SectionKey) => essaySection(sectionTitles[key], paragraphs[key]);
  return { title, sections: { ア: section("ア"), イ: section("イ"), ウ: section("ウ") }, reuse };
}

