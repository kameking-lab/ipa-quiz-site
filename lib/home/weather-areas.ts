export const WEATHER_REGION_HEADERS = ["x-vercel-ip-country", "x-vercel-ip-country-region"] as const;

export function forecastArea(headers: Headers) {
  const [country, region] = WEATHER_REGION_HEADERS.map(name => headers.get(name));
  if (country !== "JP" || !region || !/^\d{2}$/.test(region)) return undefined;
  return prefectureAreas[region];
}
