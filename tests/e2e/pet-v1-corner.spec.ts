import { expect, test } from "@playwright/test";
const quiz = "/quiz?mode=year&exam=ap&year=2023&season=spring&session=am";
const key = "ipa-quiz:pet-profiles:v1:guest";
test.use({ isMobile: true, hasTouch: true, viewport: { width: 390, height: 844 } });
for (const width of [320, 390]) test(`the same local child follows answers and the room; controls don't reward (${width}px)`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.route("**/api/auth/session", route => route.fulfill({ json: {} }));
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(quiz);
  await page.waitForURL(url => url.searchParams.get("question") === "ap-2023h-am-q1");
  await page.getByRole("radio").first().tap();
  await expect(page.locator('[aria-label="解答結果"]')).toBeFocused();
  const corner = page.locator("section[data-pet-id]");
  await corner.evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
  await expect(corner).toHaveAttribute("data-pet-id", '["guest","ap"]', { timeout: 15000 });
  await expect(corner).toHaveAttribute("data-pet-pose", "correct", { timeout: 15000 });
  await expect(corner).toHaveAttribute("data-pet-pose", "study", { timeout: 2000 });
  const box = await corner.boundingBox();
  expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(width);
  expect(box!.height).toBe(264);
  const raw = await page.evaluate(key => localStorage.getItem(key), key);
  await corner.getByRole("button", { name: "ひと休み", exact: true }).tap();
  await expect(corner).toHaveAttribute("data-pet-pose", "rest");
  await expect(corner).toHaveAttribute("data-pet-pose", "study", { timeout: 7000 });
  expect(await page.evaluate(key => localStorage.getItem(key), key)).toBe(raw);
  await page.screenshot({ path: `test-results/pet-v1/${process.env.PET_EVIDENCE_PHASE ?? "regression"}-corner-${width}.png` });
  await page.reload();
  await expect(corner).toHaveAttribute("data-pet-id", '["guest","ap"]', { timeout: 15000 });
  await expect(corner).toHaveAttribute("data-pet-pose", "study");
  await expect(corner).toHaveAttribute("data-moving", "false");
  await page.goto("/");
  await expect(corner).toHaveAttribute("data-pet-id", '["guest","ap"]', { timeout: 15000 });
  await expect(corner).toHaveAttribute("data-pet-pose", "study");
  await corner.getByRole("button", { name: "チワワのひと休みを閉じる" }).tap();
  await page.goto(quiz);
  await expect(page.getByRole("button", { name: "チワワのひと休みを開く" })).toBeVisible();
  await page.getByRole("radio").first().tap();
  await page.getByRole("button", { name: /^(次の問題へ|結果を見る)/ }).first().tap();
  await page.waitForURL(url => url.searchParams.get("question") !== "ap-2023h-am-q1");
  await page.getByRole("radio").first().tap();
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).profiles.find((profile: { qualificationId: string }) => profile.qualificationId === "ap").growth, key), { timeout: 15000 }).toBeGreaterThan(3);
  await page.getByRole("button", { name: "チワワのひと休みを開く" }).tap();
  await expect(corner).toHaveAttribute("data-pet-pose", "study");
  expect(errors).toEqual([]);
});
