export function workedExampleSource(example: WorkedExample) {
  const match = /^(\w+)-(\d{4})(cbt|h|a)-(am2?|kamoku-[ab])-q(\d+)$/.exec(example.questionId);
  if (!match) throw new Error(`Unsupported worked example: ${example.questionId}`);
  const [, exam, year, term, session, number] = match;
  const season = term === "h" ? "spring" : term === "a" ? "autumn" : "cbt";
  const file = `${year}r${String(Number(year) - 2018).padStart(2, "0")}${term === "cbt" ? "" : term}_${exam}_${exam === "ip" || exam === "sg" ? "" : `${session!.replace("-", "_")}_`}qs.pdf`;
  const base = exam === "ip"
    ? "https://www3.jitec.ipa.go.jp/JitesCbt/html/openinfo/pdf/questions/"
    : term === "cbt"
      ? "https://www.ipa.go.jp/shiken/mondai-kaiotu/sg_fe/koukai/tbl5kb0000005r9r-att/"
      : "https://www.ipa.go.jp/shiken/mondai-kaiotu/nl10bi0000009lh8-att/";
  const paper = session === "kamoku-a" ? "科目A" : session === "kamoku-b" ? "科目B" : session === "am2" ? "午前Ⅱ" : "午前";
  return {
    questionPath: `/q/${exam}/${year}-${season}/${session}/q${number}`,
    label: `${year}年度${season === "spring" ? "春期" : season === "autumn" ? "秋期" : "公開問題"} ${paper} 問${number}`,
    questionPdf: base + file,
    answerPdf: base + file.replace(/_qs\.pdf$/, "_ans.pdf"),
  };
}

