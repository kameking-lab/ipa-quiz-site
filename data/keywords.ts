/**
 * SEO 用ロングテール キーワードページ。
 * 検索ボリュームのある複合語に対し、特化ランディングを生成する。
 * 内容は public な情報の整理・実体験ベースの解説で、文字数 800〜1,500 字を目安。
 */
export interface KeywordPage {
  /** URL slug（ASCII 推奨） */
  slug: string;
  /** ページ H1 と meta title 用 */
  title: string;
  /** meta description（80〜140 字） */
  description: string;
  /** 関連試験区分コード */
  exams: string[];
  /** 関連トピックタグ（/topics へリンク） */
  relatedTopics: string[];
  /** ページ本文の段落（マークダウン無し、改行で段落区切り） */
  body: string[];
  /**
   * 戦略ページへの送客 CTA（任意・誇大回避のため明示オプトイン）。
   * "essay" = 旗艦＝午後II論述 AI 採点 /essay（論文区分 ST/SA/PM/SM/AU の論述テーマ記事のみ）。
   * "kamoku-b" = 土台＝基本情報 科目B 完全対策ピラー（FE 科目B 擬似言語記事のみ）。
   */
  strategicCta?: "essay" | "kamoku-b";
  /**
   * このトピックを深掘りする自然な親ブログ記事の slug（任意・明示オプトイン）。
   * 薄い LP（800〜1,500 字）から、同一トピックを厚く論じる /blog/<slug> 解説へ
   * 「さらに深く学ぶ」逆方向リンクを張り、LP の dead-end を解消してクロール深度を上げる。
   * 必ず実在する blog slug を指定すること（regression test で resolvability を pin）。
   */
  relatedBlogSlug?: string;
}

